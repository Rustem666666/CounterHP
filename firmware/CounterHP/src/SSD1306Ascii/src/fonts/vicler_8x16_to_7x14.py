# -----------------------------
# Функции конверсии
# -----------------------------
def convert_char_8x16_to_7x14(char_bytes):
    """Конвертирует один символ 8x16 → 7x14"""
    if len(char_bytes) != SRC_FONT_HEIGHT:
        raise ValueError(f"Неверная длина символа: {len(char_bytes)} байт, ожидалось {SRC_FONT_HEIGHT}")
    
    new_bytes = []
    for y in range(DST_FONT_HEIGHT):  # берём только 14 строк
        b = char_bytes[y]
        # Обрезаем последний бит справа, оставляем только 7 бит
        new_bytes.append(b >> 1 & 0x7F)
    return new_bytes

def convert_font(src_font):
    """Конвертирует весь шрифт"""
    dst_font = []
    for char in src_font:
        dst_font.extend(convert_char_8x16_to_7x14(char))
    return dst_font

def generate_progmeme(dst_font):
    """Генерирует текст для Arduino .h файла"""
    lines = []
    lines.append("#pragma once")
    lines.append("#include <inttypes.h>")
    lines.append("#include <avr/pgmspace.h>\n")
    lines.append(f"#define VICLER7X14_WIDTH {DST_FONT_WIDTH}")
    lines.append(f"#define VICLER7X14_HEIGHT {DST_FONT_HEIGHT}\n")
    lines.append("static const uint8_t Vicler7x14[] PROGMEM = {")
    
    # Разбиваем на строки по 16 байт для читаемости
    for i in range(0, len(dst_font), 16):
        line_bytes = dst_font[i:i+16]
        line_str = ", ".join(f"0x{b:02X}" for b in line_bytes)
        lines.append("    " + line_str + ",")
    
    lines.append("};")
    return "\n".join(lines)

