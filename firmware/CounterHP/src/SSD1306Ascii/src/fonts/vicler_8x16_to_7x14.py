    if total_bytes % SRC_FONT_HEIGHT != 0:
        print(f"Ошибка: количество байт ({total_bytes}) не кратно высоте символа ({SRC_FONT_HEIGHT})")
        sys.exit(1)
    
    # Разбиваем большой список на символы
    num_chars = total_bytes // SRC_FONT_HEIGHT
    Vicler8x16_chars = [
        Vicler8x16[i*SRC_FONT_HEIGHT:(i+1)*SRC_FONT_HEIGHT] 
        for i in range(num_chars)
    ]
    
    # Конвертируем
    dst_font = convert_font(Vicler8x16_chars)
    out_text = generate_progmeme(dst_font)
    
    # Сохраняем в файл
    with open("Vicler7x14.h", "w") as f:
        f.write(out_text)

